    @MainActor
    func testMonitorDiscardsChangedSnapshotAndResetsRetryBudgetForNewCopy() async {
        var count = 0
        var reads = 0
        let received = expectation(description: "current copy captured")
        let monitor = ClipboardHistoryMonitor(readChangeCount: { count }, readSnapshot: {
            reads += 1
            if reads == 1 {
                count = 2
                return self.readableSnapshot("stale")
            }
            if reads < 4 { return .unavailable }
            return self.readableSnapshot("current")
        })
        monitor.onCapture = { capture in
            XCTAssertEqual(capture.item.plainText, "current")
            received.fulfill()
        }
        monitor.start(enabled: true)
        defer { monitor.stop() }
        count = 1
        for _ in 0..<5 { monitor.poll() }
        await fulfillment(of: [received], timeout: 2)
        XCTAssertEqual(reads, 4)
    }

    @MainActor
    func testDisablingAndReenablingMonitorAbandonsPendingCopy() {
        var count = 0
        var reads = 0
        let monitor = ClipboardHistoryMonitor(readChangeCount: { count }, readSnapshot: {
            reads += 1
            return .unavailable
        })
        monitor.start(enabled: true)
        defer { monitor.stop() }
        count = 1
        monitor.poll()
        monitor.setEnabled(false)
        monitor.poll()
        monitor.setEnabled(true)
        monitor.poll()
        XCTAssertEqual(reads, 1)
        count = 2
        monitor.poll()
        XCTAssertEqual(reads, 2)
    }

    @MainActor
    func testDisablingDuringSnapshotReadDoesNotDeliverOrConsumeLaterCopy() async {
        var count = 0
        var reads = 0
        var monitor: ClipboardHistoryMonitor?
        let received = expectation(description: "only the later enabled copy is delivered")
        monitor = ClipboardHistoryMonitor(readChangeCount: { count }, readSnapshot: {
            reads += 1
            if reads == 1 { monitor?.setEnabled(false) }
            return self.readableSnapshot(reads == 1 ? "disabled" : "enabled")
        })
        monitor?.onCapture = { capture in
            XCTAssertEqual(capture.item.plainText, "enabled")
            received.fulfill()
        }
        monitor?.start(enabled: true)
        defer { monitor?.stop(); monitor = nil }
        count = 1
        monitor?.poll()
        monitor?.setEnabled(true)
        monitor?.poll()
        count = 2
        monitor?.poll()
        await fulfillment(of: [received], timeout: 2)
        XCTAssertEqual(reads, 2)
    }

    private func readableSnapshot(_ text: String) -> ClipboardHistoryCaptureService.ReadResult {
        .captured(.init(payloads: [
            .init(itemIndex: 0, typeIdentifier: NSPasteboard.PasteboardType.string.rawValue,
                  data: Data(text.utf8))
        ], plainText: text, imageData: nil, fileNames: [], hasRichText: false,
                       sourceBundleIdentifier: nil, sourceName: nil, copiedAt: Date()))
    }

    func testPlainTextSurvivesProviderBecomingUnavailableAfterFirstRead() {
        var reads = 0
        let text = ClipboardHistoryCaptureService.firstAvailablePlainText(in: [0]) { _ in
            reads += 1
            return reads == 1 ? "remote clipboard text" : nil
        }
        XCTAssertEqual(text, "remote clipboard text")
        XCTAssertEqual(reads, 1)
    }

    func testPlainTextReadsEachItemOnceAndStopsAtFirstAvailableValue() {
        var reads: [Int: Int] = [:]
        let text = ClipboardHistoryCaptureService.firstAvailablePlainText(in: [0, 1, 2]) { item in
            reads[item, default: 0] += 1
            return item == 1 && reads[item] == 1 ? "available" : nil
        }
        XCTAssertEqual(text, "available")
        XCTAssertEqual(reads, [0: 1, 1: 1])
    }

    func testUnavailablePlainTextIsNotRetriedOrForceUnwrapped() {
        var reads: [Int: Int] = [:]
        let text = ClipboardHistoryCaptureService.firstAvailablePlainText(in: [0, 1]) { item in
            reads[item, default: 0] += 1
            // A later read might succeed, but it is not part of this snapshot.
            return reads[item] == 1 ? nil : "new clipboard contents"
        }
        XCTAssertNil(text)
        XCTAssertEqual(reads, [0: 1, 1: 1])
    }

    func testEmptyPlainTextRemainsAnAvailableRepresentation() {
        var reads = 0
        let text = ClipboardHistoryCaptureService.firstAvailablePlainText(in: [0, 1]) { _ in
            reads += 1
            return ""
        }
        XCTAssertEqual(text, "")
        XCTAssertEqual(reads, 1)
    }

    func testEmptyPasteboardItemsDoNotReadProvider() {
