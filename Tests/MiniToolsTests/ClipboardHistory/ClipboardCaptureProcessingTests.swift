    func testSnapshotPreservesReadableTextWhenRawProviderDisappears() throws {
        var stringReads = 0
        var dataReads = 0
        let result = ClipboardHistoryCaptureService.read(
            items: [0], types: { _ in [.string] },
            string: { _, _ in
                stringReads += 1
                return stringReads == 1 ? "copied text" : nil
            },
            data: { _, _ in dataReads += 1; return nil }
        )
        guard case let .captured(snapshot) = result else {
            return XCTFail("The already-read text must produce a usable capture")
        }
        let capture = try XCTUnwrap(ClipboardHistoryCaptureService.process(snapshot))
        XCTAssertEqual(capture.item.plainText, "copied text")
        XCTAssertEqual(capture.payloads.count, 1)
        XCTAssertEqual(capture.payloads[0].data, Data("copied text".utf8))
        XCTAssertEqual(stringReads, 1)
        XCTAssertEqual(dataReads, 1)
        let objects = try XCTUnwrap(ClipboardHistoryCaptureService.itemForWriting(
            capture.item, payloads: capture.payloads, plainTextOnly: false
        ))
        XCTAssertEqual(objects.first?.string(forType: .string), "copied text")
    }

    func testSnapshotDoesNotAttachTextFallbackToAnotherItem() {
        let result = ClipboardHistoryCaptureService.read(
            items: [0, 1], types: { _ in [.string] },
            string: { item, _ in item == 1 ? "second item" : nil },
            data: { _, _ in Data() }
        )
        guard case let .captured(snapshot) = result else { return XCTFail("Missing fallback") }
        XCTAssertEqual(snapshot.payloads.map(\.itemIndex), [1])
        XCTAssertEqual(snapshot.payloads.first?.data, Data("second item".utf8))
    }

    func testSnapshotKeepsOriginalRawTextRepresentation() {
        let original = Data("original representation".utf8)
        let result = ClipboardHistoryCaptureService.read(
            items: [0], types: { _ in [.string] },
            string: { _, _ in "string representation" }, data: { _, _ in original }
        )
        guard case let .captured(snapshot) = result else { return XCTFail("Missing capture") }
        XCTAssertEqual(snapshot.payloads.first?.data, original)
    }

    func testSnapshotDistinguishesUnavailableSupportedDataFromIgnoredFormats() {
        let result = ClipboardHistoryCaptureService.read(
            items: [0], types: { _ in [.string] },
            string: { _, _ in nil }, data: { _, _ in nil }
        )
        guard case .unavailable = result else {
            return XCTFail("A provider that has not supplied its text needs a bounded retry")
        }
        let empty = ClipboardHistoryCaptureService.read(
            items: [Int](), types: { _ in [] },
            string: { _, _ in nil }, data: { _, _ in nil }
        )
        guard case .unavailable = empty else {
            return XCTFail("An unmaterialized item list needs a bounded retry")
        }
    }

    func testSnapshotIgnoresPrivateAndUnsupportedTypesWithoutReadingContent() {
        for type in [ClipboardHistoryCaptureService.markerType,
                     .init("org.nspasteboard.TransientType"),
                     .init("org.nspasteboard.ConcealedType"),
                     .init("org.nspasteboard.AutoGeneratedType")] {
            let result = ClipboardHistoryCaptureService.read(
                items: [0], types: { _ in [.string, type] },
                string: { _, _ in XCTFail("Private content must not be read"); return nil },
                data: { _, _ in XCTFail("Private content must not be read"); return nil }
            )
            guard case .ignored = result else { return XCTFail("Privacy marker not respected") }
        }
        let unsupported = ClipboardHistoryCaptureService.read(
            items: [0], types: { _ in [.init("com.example.private")] },
            string: { _, _ in XCTFail("Unsupported text must not be read"); return nil },
            data: { _, _ in XCTFail("Unsupported data must not be read"); return nil }
        )
        guard case .ignored = unsupported else { return XCTFail("Unsupported content was not ignored") }
    }

    @MainActor
    func testMonitorRetriesUnavailableCopyWithoutAnotherChangeCountAndDeliversOnce() async {
        var count = 0
        var reads = 0
        var values: [String] = []
        let received = expectation(description: "delayed copy captured")
        let monitor = ClipboardHistoryMonitor(readChangeCount: { count }, readSnapshot: {
            reads += 1
            return ClipboardHistoryCaptureService.read(
                items: [0], types: { _ in [.string] },
                string: { _, _ in reads == 1 ? nil : "delayed" },
                data: { _, _ in nil }
            )
        })
        monitor.onCapture = { capture in
            values.append(capture.item.plainText ?? "")
            received.fulfill()
        }
        monitor.start(enabled: true)
        defer { monitor.stop() }
        count = 1
        monitor.poll()
        monitor.poll()
        monitor.poll()
        await fulfillment(of: [received], timeout: 2)
        XCTAssertEqual(reads, 2)
        XCTAssertEqual(values, ["delayed"])
    }

    @MainActor
    func testMonitorBoundsUnavailableReadsAndContinuesWithNextCopy() async {
        var count = 0
        var reads = 0
        var errors = 0
        let received = expectation(description: "next copy captured")
        let monitor = ClipboardHistoryMonitor(readChangeCount: { count }, readSnapshot: {
            reads += 1
            return count == 1 ? .unavailable : self.readableSnapshot("next")
        })
        monitor.onError = { _ in errors += 1 }
        monitor.onCapture = { capture in
            XCTAssertEqual(capture.item.plainText, "next")
            received.fulfill()
        }
        monitor.start(enabled: true)
        defer { monitor.stop() }
        count = 1
        for _ in 0..<8 { monitor.poll() }
        XCTAssertEqual(reads, 3)
        XCTAssertEqual(errors, 1)
        count = 2
        monitor.poll()
        await fulfillment(of: [received], timeout: 2)
        XCTAssertEqual(reads, 4)
    }

    @MainActor
    func testMonitorDoesNotRetryIgnoredCopies() {
        var count = 0
